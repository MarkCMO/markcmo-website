// scripts/build-site-chrome.js
// Reads nav.html and footer.html and writes functions/_lib/site-chrome.js
// which exports the HTML strings for server-side injection.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const navHtml    = fs.readFileSync(path.join(ROOT, 'nav.html'),    'utf-8');
const footerHtml = fs.readFileSync(path.join(ROOT, 'footer.html'), 'utf-8');

// Escape backticks and ${ for JS template literals
function esc(str) {
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

// Extract just the <footer>…</footer> element (strip the leading <style> block)
// so we can replace footer-mega without duplicating the stylesheet.
const footerElementMatch = footerHtml.match(/<footer>[\s\S]*<\/footer>/);
const footerElement = footerElementMatch ? footerElementMatch[0] : footerHtml;

const out = `// AUTO-GENERATED by scripts/build-site-chrome.js — do not edit manually.
// Run: node scripts/build-site-chrome.js

/** Full nav.html (style + nav + script) injected into pages missing a nav */
export const SITE_NAV_HTML = \`${esc(navHtml)}\`;

/** Full footer.html (style + footer) injected into pages missing any footer */
export const SITE_FOOTER_HTML = \`${esc(footerHtml)}\`;

/** Just the <footer>…</footer> element — used to REPLACE old footer-mega blocks */
export const SITE_FOOTER_ELEMENT = \`${esc(footerElement)}\`;
`;

const outPath = path.join(ROOT, 'functions', '_lib', 'site-chrome.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out, 'utf-8');
console.log('Written:', outPath, `(${out.length} bytes)`);
